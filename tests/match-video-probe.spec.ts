/* -------------------------------------------------------------------------
 * Bounded reads over virtual large sources
 * ---------------------------------------------------------------------- */

/**
 * A multi-gigabyte MP4 that does not exist.
 *
 * The real tail-metadata fixture's `mdat` is inflated to `paddingBytes`, so the
 * file claims to be about 3 GiB while only its header and its trailing `moov`
 * are ever materialised. Everything between them reads as zeros — which is
 * exactly what a parser that respects the sample table never asks for.
 */
function virtualLargeMp4(paddingBytes: number): MediaByteSource & {
  reads: RecordedRead[];
} {
  const real = fixture("h264-tail.mp4");
  const boxes = topLevelBoxes(real);
  const mdat = boxes.find((box) => box.type === "mdat");
  const moov = boxes.find((box) => box.type === "moov");
  if (!mdat || !moov) throw new Error("fixture layout changed");

  const head = real.slice(0, mdat.start + mdat.size);
  new DataView(head.buffer).setUint32(mdat.start, mdat.size + paddingBytes);
  const tail = real.slice(moov.start);

  const padStart = mdat.start + mdat.size;
  const padEnd = padStart + paddingBytes;
  const reads: RecordedRead[] = [];

  return {
    reads,
    byteLength: padEnd + tail.byteLength,
    prefetchProfile: "network",
    async read(start, end) {
      reads.push({ start, end });
      const out = new Uint8Array(end - start);
      for (let at = start; at < end; at++) {
        if (at < padStart) out[at - start] = head[at];
        else if (at >= padEnd) out[at - start] = tail[at - padEnd];
      }
      return out;
    },
  };
}

test("a 3 GiB file is inspected without reading 3 GiB", async () => {
  const source = virtualLargeMp4(3 * 1024 * 1024 * 1024);
  const result = await inspectMedia(source);

  if (!result.ok) throw new Error(`refused: ${result.error.detail}`);
  expect(result.value.durationSeconds).toBeCloseTo(FIXTURE_DURATION_SECONDS, 2);

  expect(result.value.bytesRead).toBeLessThan(MEDIA_PROBE_MAX_TOTAL_BYTES);
  expect(result.value.rangeRequests).toBeLessThanOrEqual(
    MEDIA_PROBE_MAX_RANGE_REQUESTS,
  );
  // The whole point: a fraction of a megabyte for a file of gigabytes.
  expect(result.value.bytesRead).toBeLessThan(1024 * 1024);
  for (const read of source.reads) {
    expect(read.end - read.start).toBeLessThanOrEqual(
      MEDIA_PROBE_MAX_CHUNK_BYTES,
    );
  }
});

/**
 * Bytes the source was asked for a second time after already supplying them.
 *
 * Re-read amplification is the thing the cache budget exists to bound, and it
 * is invisible in `bytesRead` alone: a file read twice and a file twice as
 * large cost the same total. Counting the overlap separates them.
 */
function refetchedBytes(reads: RecordedRead[]): number {
  const seen: RecordedRead[] = []; // kept disjoint and sorted
  let repeated = 0;
  for (const read of reads) {
    for (const span of seen) {
      const start = Math.max(read.start, span.start);
      const end = Math.min(read.end, span.end);
      if (end > start) repeated += end - start;
    }
    seen.push({ ...read });
    seen.sort((a, b) => a.start - b.start);
    for (let i = 1; i < seen.length;) {
      if (seen[i].start <= seen[i - 1].end) {
        seen[i - 1].end = Math.max(seen[i - 1].end, seen[i].end);
        seen.splice(i, 1);
      } else {
        i++;
      }
    }
  }
  return repeated;
}

test("the cache budget is what keeps a revisited region from being refetched", async () => {
  // This file is read out of order by construction: the parser takes the head,
  // jumps three gigabytes to the trailing `moov`, and then walks that metadata
  // repeatedly for the duration, the first timestamp and the codec. Whether
  // those revisits cost the source anything is decided by one number — the
  // cache size `inspectMedia` hands Mediabunny — so running the same parse at
  // the production budget and with the cache disabled is what proves the
  // number governs rather than merely being declared.
  const padding = 3 * 1024 * 1024 * 1024;

  const bounded = virtualLargeMp4(padding);
  const withCache = await inspectMedia(bounded);
  if (!withCache.ok) throw new Error(`refused: ${withCache.error.detail}`);

  const unbounded = virtualLargeMp4(padding);
  const withoutCache = await inspectMedia(unbounded, { cacheBytes: 0 });
  if (!withoutCache.ok)
    throw new Error(`refused: ${withoutCache.error.detail}`);

  // Same file, same answer: amplification is the only difference between them.
  expect(withoutCache.value.durationSeconds).toBeCloseTo(
    withCache.value.durationSeconds,
    6,
  );

  // At the production budget every byte is fetched once, and the reason is the
  // budget: the whole working set fits inside it with room to spare.
  expect(refetchedBytes(bounded.reads)).toBe(0);
  expect(withCache.value.bytesRead).toBeLessThanOrEqual(
    MEDIA_PROBE_CACHE_BYTES,
  );

  // Take the cache away and the same parse pulls the same regions again.
  expect(refetchedBytes(unbounded.reads)).toBeGreaterThan(0);
  expect(withoutCache.value.bytesRead).toBeGreaterThan(
    withCache.value.bytesRead,
  );
  expect(unbounded.reads.length).toBeGreaterThan(bounded.reads.length);
});

test("an oversized metadata region trips the byte budget", async () => {
  // A `moov` that claims 64 MiB. Structurally legal, twice the budget, and the
  // shape a hostile file uses to make a parser allocate.
  const real = fixture("h264-faststart.mp4");
  const boxes = topLevelBoxes(real);
  const moov = boxes.find((box) => box.type === "moov");
  if (!moov) throw new Error("fixture layout changed");

  const claimed = 64 * 1024 * 1024;
  const head = real.slice(0, moov.start + moov.size);
  new DataView(head.buffer).setUint32(moov.start, claimed);
  const reads: RecordedRead[] = [];
  const source: MediaByteSource = {
    byteLength: moov.start + claimed,
    async read(start, end) {
      reads.push({ start, end });
      const out = new Uint8Array(end - start);
      for (let at = start; at < end && at < head.byteLength; at++) {
        out[at - start] = head[at];
      }
      return out;
    },
  };

  const result = await inspectMedia(source);
  expect(result.ok).toBe(false);
  if (result.ok) return;
  expect(result.error.code).toBe("media_probe_budget");
  expect(result.error.detail).toBe("total_bytes_limit");
  // The guidance a structural refusal gives is the MP4 export, not "try again".
  expect(result.error.message).toContain("Export it as an MP4");

  const total = reads.reduce((sum, read) => sum + (read.end - read.start), 0);
  expect(total).toBeLessThanOrEqual(MEDIA_PROBE_MAX_TOTAL_BYTES);
  expect(reads.length).toBeLessThanOrEqual(MEDIA_PROBE_MAX_RANGE_REQUESTS);
});

test("a box chain that never ends trips the request budget", async () => {
  // Thousands of tiny top-level boxes ahead of the metadata. Every byte is
  // legal and the file is small, so no size or byte limit catches it — only
  // counting the reads does. Without that counter this walks forever.
  const real = fixture("h264-faststart.mp4");
  const ftypSize = topLevelBoxes(real)[0].size;
  const fillerCount = 2000;
  const filler = new Uint8Array(fillerCount * 16);
  const fillerView = new DataView(filler.buffer);
  for (let i = 0; i < fillerCount; i++) {
    fillerView.setUint32(i * 16, 16);
    filler.set([0x66, 0x72, 0x65, 0x65], i * 16 + 4); // "free"
  }
  const padded = new Uint8Array(real.byteLength + filler.byteLength);
  padded.set(real.subarray(0, ftypSize), 0);
  padded.set(filler, ftypSize);
  padded.set(real.subarray(ftypSize), ftypSize + filler.byteLength);

  let reads = 0;
  const source: MediaByteSource = {
    byteLength: padded.byteLength,
    async read(start, end) {
      reads += 1;
      return padded.subarray(start, end);
    },
  };

  const result = await inspectMedia(source);
  expect(result.ok).toBe(false);
  if (!result.ok) {
    expect(result.error.code).toBe("media_probe_budget");
    expect(result.error.detail).toBe("range_request_limit");
  }
  expect(reads).toBe(MEDIA_PROBE_MAX_RANGE_REQUESTS);
});

test("the deadline ends a parse that will not finish", async () => {
  let aborted = false;
  const source: MediaByteSource = {
    byteLength: fixture("h264-faststart.mp4").byteLength,
    read(_start, _end, signal) {
      return new Promise((_resolve, reject) => {
        signal.addEventListener("abort", () => {
          aborted = true;
          reject(new Error("aborted"));
        });
      });
    },
  };

  const started = Date.now();
  const result = await inspectMedia(source, { deadlineMs: 250 });
  expect(Date.now() - started).toBeLessThan(5000);
  expect(aborted).toBe(true);
  expect(result.ok).toBe(false);
  if (!result.ok) {
    expect(result.error.code).toBe("media_probe_budget");
    expect(result.error.detail).toBe("deadline_exceeded");
  }
});

