/**
 * The attachment's duration is the one number the whole feature rests on: it
 * decides whether the recording covers the match and it bounds every seek the
 * match room performs. A wrong duration does not look broken — playback simply
 * lands somewhere else — so it is parsed from the container here, from the
 * VIDEO track, and never taken from a client or from an audio stream.
 *
 * The other half of this spec is that the parse stays bounded. The input is a
 * file a stranger chose; a crafted container can ask a parser to read forever.
 * The virtual-source tests below run the inspector against files that claim to
 * be gigabytes without a byte of that ever existing.
 *
 * Fixtures are generated by `tests/fixtures/match-video/generate.mjs` — owned,
 * synthesised, tiny. Read its header before changing them.
 */

const FIXTURES = resolve("tests/fixtures/match-video");

function fixture(name: string): Uint8Array {
  return new Uint8Array(readFileSync(resolve(FIXTURES, name)));
}

/** Every generated clip is exactly sixty frames at 30 fps. */
const FIXTURE_DURATION_SECONDS = 2;

/* -------------------------------------------------------------------------
 * Test doubles
 * ---------------------------------------------------------------------- */

interface RecordedRead {
  start: number;
  end: number;
}

/** A byte source that records every read it is asked to perform. */
function recordingSource(
  bytes: Uint8Array,
): MediaByteSource & { reads: RecordedRead[] } {
  const reads: RecordedRead[] = [];
  return {
    reads,
    byteLength: bytes.byteLength,
    async read(start, end) {
      reads.push({ start, end });
      return bytes.subarray(start, end);
    },
  };
}

/** The minimum of `File` the inspector may touch, with slicing recorded. */
type FakeFile = SliceableFile & {
  slices: RecordedRead[];
  wholeFileReads: number;
  arrayBuffer(): Promise<ArrayBuffer>;
};

function fakeFile(name: string, bytes: Uint8Array): FakeFile {
  const slices: RecordedRead[] = [];
  return {
    name,
    size: bytes.byteLength,
    type: "video/mp4",
    slices,
    wholeFileReads: 0,
    slice(start: number, end: number) {
      slices.push({ start, end });
      return {
        async arrayBuffer() {
          const copy = bytes.slice(start, end);
          return copy.buffer.slice(
            copy.byteOffset,
            copy.byteOffset + copy.byteLength,
          ) as ArrayBuffer;
        },
      };
    },
    /** A `File` has this. Touching it is the bug these tests exist to catch. */
    async arrayBuffer() {
      this.wholeFileReads += 1;
      return bytes.buffer as ArrayBuffer;
    },
  };
}

/* -------------------------------------------------------------------------
 * ISO-BMFF box walking, used to build the virtual large file
 * ---------------------------------------------------------------------- */

interface Box {
  type: string;
  start: number;
  size: number;
}

/** Top-level boxes only. Enough to find `moov` and `mdat`. */
function topLevelBoxes(bytes: Uint8Array): Box[] {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const boxes: Box[] = [];
  let at = 0;
  while (at + 8 <= bytes.byteLength) {
    const size = view.getUint32(at);
    const type = String.fromCharCode(...bytes.subarray(at + 4, at + 8));
    if (size < 8) break;
    boxes.push({ type, start: at, size });
    at += size;
  }
  return boxes;
}

